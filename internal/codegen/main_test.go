package codegen_test

import (
	"testing"

	"github.com/lucindo/dynaflux/internal/catalog"
	"github.com/lucindo/dynaflux/internal/codegen"
)

// The runtime binary's main.go calls fluxruntime.Run with the client package's Catalog,
// which it imports under the package's name when the import path ends in another one.
func TestMainGolden(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name, importPath, command, pkg, want string
	}{
		{"defaults", "example.com/app/internal/flux", "dynaflux-runtime", "flux", `// Code generated by dynaflux v0.0.0-test. DO NOT EDIT.

// Command dynaflux-runtime is the Lambda binary of store analytics. Each function sets
// DYNAFLUX_MODE to choose what it serves.
package main

import (
	"log"

	"github.com/lucindo/dynaflux/fluxruntime"

	"example.com/app/internal/flux"
)

func main() {
	if err := fluxruntime.Run(flux.Catalog); err != nil {
		log.Fatal(err)
	}
}
`},
		{"package named apart from its directory", "example.com/app/pkg/internal/gen", "rt", "client", `// Code generated by dynaflux v0.0.0-test. DO NOT EDIT.

// Command rt is the Lambda binary of store analytics. Each function sets
// DYNAFLUX_MODE to choose what it serves.
package main

import (
	"log"

	"github.com/lucindo/dynaflux/fluxruntime"

	client "example.com/app/pkg/internal/gen"
)

func main() {
	if err := fluxruntime.Run(client.Catalog); err != nil {
		log.Fatal(err)
	}
}
`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			got, err := codegen.Main(&catalog.Catalog{Store: "analytics"}, tt.importPath, tt.command,
				codegen.Options{Package: tt.pkg, Version: "v0.0.0-test"})
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != tt.want {
				t.Errorf("main.go:\n%s\nwant:\n%s", got, tt.want)
			}
		})
	}
}
