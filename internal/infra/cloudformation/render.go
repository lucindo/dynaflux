// Package cloudformation renders an infrastructure manifest as CloudFormation templates,
// which docs/spec/infra.md describes. It adds only CloudFormation's mechanics: every value
// that matters to data or safety comes from the manifest. The same manifest gives the same
// bytes.
package cloudformation

import (
	"errors"
	"fmt"

	"go.yaml.in/yaml/v4"

	"github.com/lucindo/dynaflux/internal/infra"
)

// Names of the files that [Render] returns.
const (
	GlobalTemplate    = "global.yaml"
	GlobalStackPolicy = "global.stack-policy.json"
	RegionalTemplate  = "regional.yaml"
)

// CloudFormation's limits on one template.
const (
	maxResources     = 500
	maxTemplateBytes = 1_000_000
)

// Render returns the files of m by name: [GlobalTemplate] and [RegionalTemplate], whose
// first line is "# Code generated by dynaflux <version>. DO NOT EDIT.", and
// [GlobalStackPolicy], a stack policy for the global stack, which as plain JSON can't carry
// that line. It fails when a template is over CloudFormation's limits.
func Render(m *infra.Manifest, version string) (map[string][]byte, error) {
	header := "# Code generated by dynaflux " + version + ". DO NOT EDIT.\n"
	files := map[string][]byte{}
	for _, t := range []struct {
		name  string
		build func(*infra.Manifest) (*resources, *yaml.Node, error)
	}{{GlobalTemplate, globalTemplate}, {RegionalTemplate, regionalTemplate}} {
		rs, doc, err := t.build(m)
		if err != nil {
			return nil, fmt.Errorf("cloudformation: %s: %w", t.name, err)
		}
		data, err := dump(doc)
		if err != nil {
			return nil, fmt.Errorf("cloudformation: %s: %w", t.name, err)
		}
		data = append([]byte(header), data...)
		if err = checkLimits(len(rs.ids), len(data)); err != nil {
			return nil, fmt.Errorf("cloudformation: %s %w", t.name, err)
		}
		files[t.name] = data
	}
	policy, err := stackPolicy(m.Global)
	if err != nil {
		return nil, fmt.Errorf("cloudformation: %s: %w", GlobalStackPolicy, err)
	}
	files[GlobalStackPolicy] = policy
	return files, nil
}

// checkLimits fails when a template is over CloudFormation's limits. An
// AWS::Serverless::Function is one resource after the SAM transform.
func checkLimits(resources, size int) error {
	const fix = "every stream and view version adds resources, so retire old view versions or split the streams across stores"
	switch {
	case resources > maxResources:
		return fmt.Errorf("has %d resources, and a CloudFormation template can have at most %d: %s", resources, maxResources, fix)
	case size > maxTemplateBytes:
		return fmt.Errorf("has %d bytes, and a CloudFormation template can have at most %d: %s", size, maxTemplateBytes, fix)
	}
	return nil
}

// template returns a template document of sections, such as Parameters, in order. A SAM
// template uses the transform for its functions.
func template(description string, sam bool, sections ...pair) *yaml.Node {
	var transform *yaml.Node
	if sam {
		transform = str("AWS::Serverless-2016-10-31")
	}
	return &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{mapping(append([]pair{
		kv("AWSTemplateFormatVersion", str("2010-09-09")),
		kv("Transform", transform),
		kv("Description", str(description)),
	}, sections...)...)}}
}

// resources is the Resources section of a template, built with r, and the first error of
// the resources added to it.
type resources struct {
	r    *resolver
	node *yaml.Node
	ids  map[string]bool
	err  error
}

func newResources(r *resolver) *resources {
	return &resources{r: r, node: mapping(), ids: map[string]bool{}}
}

// add adds the resource that build returns, unless a text of it didn't resolve. Two
// resources with one ID would be one resource to CloudFormation.
func (rs *resources) add(id string, build func() *yaml.Node) {
	if rs.err != nil {
		return
	}
	n := build()
	err := rs.r.err
	if err == nil && rs.ids[id] {
		err = errors.New("two resources have this ID")
	}
	if err != nil {
		rs.err = fmt.Errorf("%s: %w", id, err)
		return
	}
	rs.ids[id] = true
	rs.node.Content = append(rs.node.Content, str(id), n)
}

// resource returns a resource of type typ with properties, after its other attributes,
// such as DeletionPolicy.
func resource(typ string, properties *yaml.Node, attrs ...pair) *yaml.Node {
	return mapping(append(append([]pair{kv("Type", str(typ))}, attrs...), kv("Properties", properties))...)
}

// deletion returns the DeletionPolicy and UpdateReplacePolicy of a resource.
func deletion(d infra.Deletion) []pair {
	switch d {
	case infra.DeletionRetain:
		return []pair{kv("DeletionPolicy", str("Retain")), kv("UpdateReplacePolicy", str("Retain"))}
	case infra.DeletionRetainExceptOnCreate:
		return []pair{kv("DeletionPolicy", str("RetainExceptOnCreate")), kv("UpdateReplacePolicy", str("Retain"))}
	case infra.DeletionDelete:
	}
	return []pair{kv("DeletionPolicy", str("Delete")), kv("UpdateReplacePolicy", str("Delete"))}
}
