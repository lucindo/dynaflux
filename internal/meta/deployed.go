// Deployed catalog items (docs/spec/encoding.md §8.4).
const (
	catalogPK        = "catalog"
	currentSK        = "current"
	bodyPKPrefix     = "catalog#"
	bodySK           = "body"
	attrBody         = "body"
	attrHash         = "hash"
	attrFormat       = "format"
	attrGenerator    = "generator"
	attrRegisteredAt = "registered_at"

	// maxCatalogBytes bounds a catalog body's decompressed size.
	maxCatalogBytes = 16 << 20
)

// ErrNoCatalog is a catalog hash with no stored body.
var ErrNoCatalog = errors.New("meta: no catalog is stored under the hash")

// Registered is the deployed catalog's current item.
type Registered struct {
	Hash      string // the lowercase hex SHA-256 of the catalog's bytes
	Generator string // the version of the Dynaflux module that generated the catalog
	Format    int    // the catalog's format
	At        time.Time
}

func currentKey() store.Key { return store.Key{PK: catalogPK, SK: currentSK} }

func bodyKey(hash string) store.Key { return store.Key{PK: bodyPKPrefix + hash, SK: bodySK} }

// RegisterCatalog stores data, the bytes catalog.Marshal returns, under its hash unless it is
// stored already, then makes it the current catalog, generated by generator.
func (m *Meta) RegisterCatalog(ctx context.Context, data []byte, generator string) (Registered, error) {
	format, err := catalogFormat(data)
	if err != nil {
		return Registered{}, err
	}
	hash := catalog.Hash(data)
	if err = m.putBody(ctx, hash, data); err != nil {
		return Registered{}, err
	}
	return m.point(ctx, Registered{Hash: hash, Generator: generator, Format: format})
}

// PointCatalog makes the catalog stored under hash the current one, generated by generator,
// as a rollback does. A hash with no stored body fails with [ErrNoCatalog].
func (m *Meta) PointCatalog(ctx context.Context, hash, generator string) error {
	data, err := m.ReadCatalog(ctx, hash)
	if err != nil {
		return err
	}
	format, err := catalogFormat(data)
	if err != nil {
		return err
	}
	_, err = m.point(ctx, Registered{Hash: hash, Generator: generator, Format: format})
	return err
}

// Current reads the current catalog's item with a consistent read, and reports whether one
// was registered.
func (m *Meta) Current(ctx context.Context) (Registered, bool, error) {
	reg, v, err := m.current(ctx)
	return reg, v > 0, err
}

// ReadCatalog reads the catalog stored under hash with a consistent read and returns its
// bytes, checked against the hash. A hash with no stored body fails with [ErrNoCatalog].
func (m *Meta) ReadCatalog(ctx context.Context, hash string) ([]byte, error) {
	if !isHash(hash) {
		return nil, fmt.Errorf("meta: read catalog %q: not a lowercase hex SHA-256", hash)
	}
	it, err := m.b.Get(ctx, m.table, bodyKey(hash), true)
	if err != nil {
		return nil, fmt.Errorf("meta: read catalog %s: %w", hash, err)
	}
	if it == nil {
		return nil, fmt.Errorf("meta: read catalog %s: %w", hash, ErrNoCatalog)
	}
	return m.decodeBody(hash, it)
}

// catalogFormat returns the format of a catalog's bytes. The bytes may be of a format this
// build can't decode, as a rollback's may.
func catalogFormat(data []byte) (int, error) {
	var probe struct {
		Format int `json:"format"`
	}
	if err := json.Unmarshal(data, &probe); err != nil {
		return 0, fmt.Errorf("meta: read the catalog's format: %w", err)
	}
	if probe.Format < 1 {
		return 0, fmt.Errorf("meta: the catalog's format is %d", probe.Format)
	}
	return probe.Format, nil
}

func isHash(s string) bool {
	b, err := hex.DecodeString(s)
	return err == nil && len(b) == sha256.Size && hex.EncodeToString(b) == s
}

// putBody stores data's body under hash, which is data's. A body stored already under the
// hash holds the same bytes, so a failed condition is success once the body checks out.
func (m *Meta) putBody(ctx context.Context, hash string, data []byte) error {
	// The bytes that generate measures against DF6019.
	body, err := catalog.Compress(data)
	if err != nil {
		return fmt.Errorf("meta: %w", err)
	}
	k := bodyKey(hash)
	it := store.Item{
		catalog.AttrPK: str(k.PK),
		catalog.AttrSK: str(k.SK),
		attrBody:       {Type: store.B, Bin: body},
	}
	err = m.b.Put(ctx, m.table, it, store.IfAbsent())
	if ce, ok := errors.AsType[*store.ConditionError](err); ok {
		_, err = m.decodeBody(hash, ce.Current)
		return err
	}
	if err != nil {
		return fmt.Errorf("meta: write catalog %s: %w", hash, err)
	}
	return nil
}

// decodeBody returns the catalog bytes of a body item, checked against hash.
func (m *Meta) decodeBody(hash string, it store.Item) ([]byte, error) {
	r := reader{attrs: it}
	r.str(catalog.AttrPK)
	r.str(catalog.AttrSK)
	body, _ := r.value(attrBody, store.B, true)
	if err := r.close(); err != nil {
		return nil, m.decodeError(it, err)
	}
	data, err := gunzip(body.Bin)
	if err == nil && catalog.Hash(data) != hash {
		err = errors.New("the body doesn't match its hash")
	}
	if err != nil {
		return nil, m.decodeError(it, err)
	}
	return data, nil
}

// gunzip decompresses at most maxCatalogBytes.
func gunzip(b []byte) ([]byte, error) {
	zr, err := gzip.NewReader(bytes.NewReader(b))
	if err != nil {
		return nil, err
	}
	data, err := io.ReadAll(io.LimitReader(zr, maxCatalogBytes+1))
	if err != nil {
		return nil, err
	}
	if len(data) > maxCatalogBytes {
		return nil, fmt.Errorf("the body holds more than %d bytes", maxCatalogBytes)
	}
	return data, nil
}

// point makes reg the current catalog, stamping its time. A current item with the same hash,
// generator and format is kept as it is.
func (m *Meta) point(ctx context.Context, reg Registered) (Registered, error) {
	if reg.Generator == "" {
		return Registered{}, fmt.Errorf("meta: register catalog %s: no generator", reg.Hash)
	}
	cur, v, err := m.current(ctx)
	if err != nil {
		return Registered{}, err
	}
	for range maxAttempts {
		if v > 0 && cur.Hash == reg.Hash && cur.Generator == reg.Generator && cur.Format == reg.Format {
			return cur, nil
		}
		reg.At = stamp(time.Now())
		err = m.b.Put(ctx, m.table, encodeCurrent(reg, v+1), cond(v))
		var ce *store.ConditionError
		if !errors.As(err, &ce) {
			if err != nil {
				return Registered{}, fmt.Errorf("meta: register catalog %s: %w", reg.Hash, err)
			}
			return reg, nil
		}
		cur, v = Registered{}, 0
		if ce.Current != nil {
			if cur, v, err = m.decodeCurrent(ce.Current); err != nil {
				return Registered{}, err
			}
		}
	}
	return Registered{}, m.errAttempts(currentKey())
}

// current reads the current item and its _v, 0 when there is none.
func (m *Meta) current(ctx context.Context) (Registered, int64, error) {
	it, err := m.b.Get(ctx, m.table, currentKey(), true)
	if err != nil {
		return Registered{}, 0, fmt.Errorf("meta: read the current catalog: %w", err)
	}
	if it == nil {
		return Registered{}, 0, nil
	}
	return m.decodeCurrent(it)
}

func encodeCurrent(reg Registered, v int64) store.Item {
	return store.Item{
		catalog.AttrPK:         str(catalogPK),
		catalog.AttrSK:         str(currentSK),
		attrHash:               str(reg.Hash),
		attrFormat:             num(int64(reg.Format)),
		attrGenerator:          str(reg.Generator),
		attrRegisteredAt:       num(micros(reg.At)),
		catalog.AttrRowVersion: num(v),
	}
}

func (m *Meta) decodeCurrent(it store.Item) (Registered, int64, error) {
	r := reader{attrs: it}
	r.str(catalog.AttrPK)
	r.str(catalog.AttrSK)
	reg := Registered{
		Hash:      r.str(attrHash),
		Generator: r.text(attrGenerator),
		Format:    int(r.count(attrFormat)),
		At:        r.instant(attrRegisteredAt, true),
	}
	if !isHash(reg.Hash) || reg.Format < 1 {
		r.failf("%s %q or %s %d is out of range", attrHash, reg.Hash, attrFormat, reg.Format)
	}
	v := r.version()
	if err := r.close(); err != nil {
		return Registered{}, 0, m.decodeError(it, err)
	}
	return reg, v, nil
}
