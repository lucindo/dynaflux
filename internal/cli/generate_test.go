var update = flag.Bool("update", false, "rewrite the want/dynaflux.lock sections from the actual output") //nolint:gochecknoglobals // go test flags are package variables

const (
	wantPrefix = "want/"
	wantLock   = wantPrefix + "dynaflux.lock"
	// goHeader and yamlHeader are the first lines of the generated Go files and templates,
	// as a test binary sees its version.
	goHeader   = "// Code generated by dynaflux (devel). DO NOT EDIT.\n"
	yamlHeader = "# Code generated by dynaflux (devel). DO NOT EDIT.\n"
)

// generatedFiles are the files generate writes with the default go.out, runtime.out and
// infra.out.
func generatedFiles() []string {
	return []string{
		"cmd/dynaflux-runtime/main.go", "dynaflux.lock", "infra/dynaflux/global.stack-policy.json", "infra/dynaflux/global.yaml",
		"infra/dynaflux/regional.yaml", "internal/flux/catalog.go", "internal/flux/client.go", "internal/flux/queries.go",
		"internal/flux/streams.go",
	}
}

// TestGenerate runs generate on each project under testdata/generate. When it succeeds,
// it writes the four files of the client package, the templates and the lock, whose bytes
// the archive's want/dynaflux.lock holds (go test -update rewrites it; review the diff).
// When it fails, it writes nothing.
func TestGenerate(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		want result // its stderr is a prefix of the actual one
	}{
		{"new", result{0, "page_daily@v1: new\n", ""}},
		{"unchanged", result{0, "", ""}},
		{"changed", result{0, "page_daily@v1: retained\npage_daily@v2: new\n", ""}},
		{"revert", result{0, "page_daily@v1: current again\npage_daily@v2: retained\n", ""}},
		{"removed", result{0, "page_daily@v1: retained\n", ""}},
		{"two_current", result{0, "page_daily@v1: retained\n", ""}},
		{"conflict", result{1, "", "dynaflux.lock:4:1: error DF6013: can't use dynaflux.lock: invalid JSON: "}},
		{"user_file", result{1, "", "dynaflux generate: internal/flux/client.go has no \"// Code generated"}},
		{
			"user_main",
			result{1, "", "dynaflux generate: cmd/dynaflux-runtime/main.go has no \"// Code generated ... DO NOT EDIT.\" line, " +
				"so it isn't generated code; move it out of cmd/dynaflux-runtime\n"},
		},
		{"no_module", result{2, "", "dynaflux generate: no go.mod in "}},
		{
			"user_template",
			result{1, "", "dynaflux generate: infra/dynaflux/global.yaml doesn't start with a \"# Code generated ... DO NOT EDIT.\" line"},
		},
		{
			"user_policy",
			result{1, "", "dynaflux generate: infra/dynaflux/global.stack-policy.json can't carry a \"# Code generated ... DO NOT EDIT.\" " +
				"line, and there is no generated global.yaml beside it"},
		},
		{"no_stream", result{1, "", "dynaflux generate: infra: the store has no stream, so there is nothing to deploy\n"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			name := "generate/" + tt.name
			dir := writeProject(t, name)
			before := snapshot(t, dir)
			got := run(dir, "generate")
			if got.status != tt.want.status || got.stdout != tt.want.stdout || !strings.HasPrefix(got.stderr, tt.want.stderr) {
				t.Fatalf("got  %+v\nwant %+v, with stderr as a prefix", got, tt.want)
			}
			after := snapshot(t, dir)
			if got.status != 0 {
				if !maps.EqualFunc(before, after, slices.Equal) {
					t.Errorf("a failed generate changed files: %q became %q", slices.Sorted(maps.Keys(before)), slices.Sorted(maps.Keys(after)))
				}
				return
			}
			checkWritten(t, before, after)
			checkLock(t, name, after["dynaflux.lock"])
		})
	}
}

// checkWritten checks that generate added exactly its files, each Go file and template
// with its header.
func checkWritten(t *testing.T, before, after map[string][]byte) {
	t.Helper()
	want := slices.Compact(slices.Sorted(slices.Values(append(slices.Collect(maps.Keys(before)), generatedFiles()...))))
	if got := slices.Sorted(maps.Keys(after)); !slices.Equal(got, want) {
		t.Errorf("files after generate: %q, want %q", got, want)
	}
	for _, p := range generatedFiles() {
		header := map[string]string{".go": goHeader, ".yaml": yamlHeader}[path.Ext(p)]
		if header != "" && !strings.HasPrefix(string(after[p]), header) {
			t.Errorf("%s doesn't start with %q", p, header)
		}
	}
}

// checkLock compares the lock that generate wrote with the archive's want/dynaflux.lock.
func checkLock(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name+".txtar")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	ar := txtar.Parse(data)
	i := slices.IndexFunc(ar.Files, func(f txtar.File) bool { return f.Name == wantLock })
	if *update {
		if i < 0 {
			ar.Files = append(ar.Files, txtar.File{Name: wantLock})
			i = len(ar.Files) - 1
		}
		ar.Files[i].Data = got
		if err = os.WriteFile(path, txtar.Format(ar), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if i < 0 {
		t.Fatalf("%s has no %s section", path, wantLock)
	}
	if want := ar.Files[i].Data; string(got) != string(want) {
		t.Errorf("dynaflux.lock:\n%s\nwant:\n%s", got, want)
	}
}

// snapshot returns every file under dir by its slash path.
func snapshot(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		files[filepath.ToSlash(rel)] = data
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

// TestGenerateExampleIsCurrent checks that the code, templates and lock committed in
// examples/analytics are what generate writes: regenerate them after changing generate.
func TestGenerateExampleIsCurrent(t *testing.T) {
	t.Parallel()
	// The example's main.go imports its client by Dynaflux's module path.
	module := t.TempDir()
	if err := os.WriteFile(filepath.Join(module, "go.mod"), []byte("module github.com/lucindo/dynaflux\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(module, "examples", "analytics")
	if err := os.CopyFS(dir, os.DirFS(filepath.Join("..", "..", "examples", "analytics"))); err != nil {
		t.Fatal(err)
	}
	before := snapshot(t, dir)
	// The example has warnings, so only stdout, which lists changed view versions, is empty.
	if got := run(dir, "generate"); got.status != 0 || got.stdout != "" {
		t.Fatalf("generate: %+v", got)
	}
	for p, data := range snapshot(t, dir) {
		if !slices.Equal(data, before[p]) {
			t.Errorf("generate changed examples/analytics/%s", p)
		}
	}
}

// main.go imports go.out by the path of the module whose go.mod is nearest above the
// project, and names the command after runtime.out.
func TestGenerateMainImportsGoOut(t *testing.T) {
	t.Parallel()
	module := t.TempDir()
	if err := os.WriteFile(filepath.Join(module, "go.mod"), []byte("// The app.\nmodule \"example.com/app\" // quoted\n\ngo 1.26\n"),
		0o644); err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(module, "svc")
	if err := os.CopyFS(dir, os.DirFS(writeProject(t, "generate/new"))); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(dir, "go.mod")); err != nil {
		t.Fatal(err)
	}
	cfg := "store: analytics\nregions: [us-east-1, us-west-2]\ngo:\n  out: pkg/internal/flux\nruntime:\n  out: pkg/cmd/rt\n"
	if err := os.WriteFile(filepath.Join(dir, "dynaflux.yaml"), []byte(cfg), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := run(dir, "generate"); got.status != 0 {
		t.Fatalf("generate: %+v", got)
	}
	main, err := os.ReadFile(filepath.Join(dir, "pkg", "cmd", "rt", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"\n// Command rt is the Lambda binary of store analytics.", "\n\t\"example.com/app/svc/pkg/internal/flux\"\n"} {
		if !strings.Contains(string(main), want) {
			t.Errorf("main.go doesn't hold %q:\n%s", want, main)
		}
	}
}

func TestGenerateLeavesUnchangedFilesAlone(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, "generate/new")
	if got := run(dir, "gen"); got.status != 0 {
		t.Fatalf("first run: %+v", got)
	}
	old := time.Date(2001, 2, 3, 4, 5, 6, 0, time.UTC)
	for _, p := range generatedFiles() {
		if err := os.Chtimes(filepath.Join(dir, p), old, old); err != nil {
			t.Fatal(err)
		}
	}
	if got := run(dir, "gen"); got != (result{0, "", ""}) {
		t.Fatalf("second run: %+v", got)
	}
	for _, p := range generatedFiles() {
		info, err := os.Stat(filepath.Join(dir, p))
		if err != nil {
			t.Fatal(err)
		}
		if !info.ModTime().Equal(old) {
			t.Errorf("%s was written again", p)
		}
	}
}

// An edited generated file is replaced, including the stack policy, which the generated
// global.yaml beside it covers. A template's edit keeps it YAML, which generate reads back.
func TestGenerateReplacesAnEditedFile(t *testing.T) {
	t.Parallel()
	for file, edit := range map[string]string{
		"internal/flux/client.go":                 "\nedited\n",
		"infra/dynaflux/global.yaml":              "\n# edited\n",
		"infra/dynaflux/global.stack-policy.json": "\nedited\n",
	} {
		t.Run(path.Base(file), func(t *testing.T) {
			t.Parallel()
			dir := writeProject(t, "generate/new")
			if got := run(dir, "generate"); got.status != 0 {
				t.Fatalf("first run: %+v", got)
			}
			p := filepath.Join(dir, filepath.FromSlash(file))
			want, err := os.ReadFile(p)
			if err != nil {
				t.Fatal(err)
			}
			if err = os.WriteFile(p, append(want, edit...), 0o644); err != nil {
				t.Fatal(err)
			}
			if got := run(dir, "generate"); got != (result{0, "", ""}) {
				t.Fatalf("second run: %+v", got)
			}
			if got, readErr := os.ReadFile(p); readErr != nil || string(got) != string(want) {
				t.Errorf("%s after generate:\n%s\nwant:\n%s", file, got, want)
			}
		})
	}
}

// TestHeaderVersion checks the version in the header of generated files, which must not
// change with each commit of a checkout or name a local path, so that generated code
// doesn't differ between two runs from one go.mod.
func TestHeaderVersion(t *testing.T) {
	t.Parallel()
	const module = "github.com/lucindo/dynaflux"
	vcs := []debug.BuildSetting{{Key: "vcs", Value: "git"}, {Key: "vcs.modified", Value: "false"}}
	shop := func(dep debug.Module) *debug.BuildInfo {
		return &debug.BuildInfo{Main: debug.Module{Path: "example.com/shop", Version: "(devel)"}, Deps: []*debug.Module{&dep}, Settings: vcs}
	}
	tests := []struct {
		name string
		bi   *debug.BuildInfo
		want string
	}{
		{"no build info", nil, "(devel)"},
		{"installed with go install", &debug.BuildInfo{Main: debug.Module{Path: module, Version: "v0.3.0"}}, "v0.3.0"},
		{
			"built from a checkout with changes",
			&debug.BuildInfo{Main: debug.Module{Path: module, Version: "v0.0.0-20261026052951-3ca2f74900fe+dirty"}, Settings: vcs},
			"(devel)",
		},
		{"built from a tagged checkout", &debug.BuildInfo{Main: debug.Module{Path: module, Version: "v0.3.0"}, Settings: vcs}, "(devel)"},
		{"run with go run", &debug.BuildInfo{Main: debug.Module{Path: module, Version: "(devel)"}}, "(devel)"},
		{"run with go tool", shop(debug.Module{Path: module, Version: "v0.3.0"}), "v0.3.0"},
		{
			"run with go tool at a commit that go.mod pins",
			shop(debug.Module{Path: module, Version: "v0.3.1-0.20261026052951-3ca2f74900fe"}),
			"v0.3.1-0.20261026052951-3ca2f74900fe",
		},
		{
			"replaced by a local directory",
			shop(debug.Module{Path: module, Version: "v0.3.0", Replace: &debug.Module{Path: "/home/ana/dynaflux"}}),
			"(devel)",
		},
		{
			"replaced by a fork",
			shop(debug.Module{Path: module, Version: "v0.3.0", Replace: &debug.Module{Path: "example.com/fork/dynaflux", Version: "v0.3.1"}}),
			"v0.3.1",
		},
		{"without the module", shop(debug.Module{Path: "example.com/other", Version: "v1.0.0"}), "(devel)"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if got := cli.HeaderVersion(tt.bi); got != tt.want {
				t.Errorf("got %q, want %q", got, tt.want)
			}
		})
	}
}
