var update = flag.Bool("update", false, "rewrite the want/dynaflux.lock sections from the actual output") //nolint:gochecknoglobals // go test flags are package variables

const (
	wantPrefix = "want/"
	wantLock   = wantPrefix + "dynaflux.lock"
	// header is the first line of each generated file, as a test binary sees its version.
	header = "// Code generated by dynaflux (devel). DO NOT EDIT.\n"
)

// generatedFiles are the files generate writes with the default go.out.
func generatedFiles() []string {
	return []string{
		"dynaflux.lock", "internal/flux/catalog.go", "internal/flux/client.go",
		"internal/flux/queries.go", "internal/flux/streams.go",
	}
}

// TestGenerate runs generate on each project under testdata/generate. When it succeeds,
// it writes the four files of the client package and the lock, whose bytes the archive's
// want/dynaflux.lock holds (go test -update rewrites it; review the diff). When it fails,
// it writes nothing.
func TestGenerate(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		want result // its stderr is a prefix of the actual one
	}{
		{"new", result{0, "page_daily@v1: new\n", ""}},
		{"unchanged", result{0, "", ""}},
		{"changed", result{0, "page_daily@v1: retained\npage_daily@v2: new\n", ""}},
		{"revert", result{0, "page_daily@v1: current again\npage_daily@v2: retained\n", ""}},
		{"removed", result{0, "page_daily@v1: retained\n", ""}},
		{"two_current", result{0, "page_daily@v1: retained\n", ""}},
		{"conflict", result{1, "", "dynaflux.lock:4:1: error DF6013: can't use dynaflux.lock: invalid JSON: "}},
		{"user_file", result{1, "", "dynaflux generate: internal/flux/client.go has no \"// Code generated"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			name := "generate/" + tt.name
			dir := writeProject(t, name)
			before := snapshot(t, dir)
			got := run(dir, "generate")
			if got.status != tt.want.status || got.stdout != tt.want.stdout || !strings.HasPrefix(got.stderr, tt.want.stderr) {
				t.Fatalf("got  %+v\nwant %+v, with stderr as a prefix", got, tt.want)
			}
			after := snapshot(t, dir)
			if got.status != 0 {
				if !maps.EqualFunc(before, after, slices.Equal) {
					t.Errorf("a failed generate changed files: %q became %q", slices.Sorted(maps.Keys(before)), slices.Sorted(maps.Keys(after)))
				}
				return
			}
			checkWritten(t, before, after)
			checkLock(t, name, after["dynaflux.lock"])
		})
	}
}

// checkWritten checks that generate added exactly its files, each Go file with the header.
func checkWritten(t *testing.T, before, after map[string][]byte) {
	t.Helper()
	want := slices.Compact(slices.Sorted(slices.Values(append(slices.Collect(maps.Keys(before)), generatedFiles()...))))
	if got := slices.Sorted(maps.Keys(after)); !slices.Equal(got, want) {
		t.Errorf("files after generate: %q, want %q", got, want)
	}
	for _, p := range generatedFiles()[1:] {
		if !strings.HasPrefix(string(after[p]), header) {
			t.Errorf("%s doesn't start with %q", p, header)
		}
	}
}

// checkLock compares the lock that generate wrote with the archive's want/dynaflux.lock.
func checkLock(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name+".txtar")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	ar := txtar.Parse(data)
	i := slices.IndexFunc(ar.Files, func(f txtar.File) bool { return f.Name == wantLock })
	if *update {
		if i < 0 {
			ar.Files = append(ar.Files, txtar.File{Name: wantLock})
			i = len(ar.Files) - 1
		}
		ar.Files[i].Data = got
		if err = os.WriteFile(path, txtar.Format(ar), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if i < 0 {
		t.Fatalf("%s has no %s section", path, wantLock)
	}
	if want := ar.Files[i].Data; string(got) != string(want) {
		t.Errorf("dynaflux.lock:\n%s\nwant:\n%s", got, want)
	}
}

// snapshot returns every file under dir by its slash path.
func snapshot(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		files[filepath.ToSlash(rel)] = data
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func TestGenerateLeavesUnchangedFilesAlone(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, "generate/new")
	if got := run(dir, "gen"); got.status != 0 {
		t.Fatalf("first run: %+v", got)
	}
	old := time.Date(2001, 2, 3, 4, 5, 6, 0, time.UTC)
	for _, p := range generatedFiles() {
		if err := os.Chtimes(filepath.Join(dir, p), old, old); err != nil {
			t.Fatal(err)
		}
	}
	if got := run(dir, "gen"); got != (result{0, "", ""}) {
		t.Fatalf("second run: %+v", got)
	}
	for _, p := range generatedFiles() {
		info, err := os.Stat(filepath.Join(dir, p))
		if err != nil {
			t.Fatal(err)
		}
		if !info.ModTime().Equal(old) {
			t.Errorf("%s was written again", p)
		}
	}
}

func TestGenerateReplacesAnEditedFile(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, "generate/new")
	if got := run(dir, "generate"); got.status != 0 {
		t.Fatalf("first run: %+v", got)
	}
	path := filepath.Join(dir, "internal", "flux", "client.go")
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(path, append(want, "\nvar x = 1\n"...), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := run(dir, "generate"); got != (result{0, "", ""}) {
		t.Fatalf("second run: %+v", got)
	}
	if got, readErr := os.ReadFile(path); readErr != nil || string(got) != string(want) {
		t.Errorf("client.go after generate:\n%s\nwant:\n%s", got, want)
	}
}

// TestHeaderVersion checks the version in the header of generated files, which must not
// change with each commit of a checkout or name a local path, so that generated code
// doesn't differ between two runs from one go.mod.
func TestHeaderVersion(t *testing.T) {
	t.Parallel()
	const module = "github.com/lucindo/dynaflux"
	vcs := []debug.BuildSetting{{Key: "vcs", Value: "git"}, {Key: "vcs.modified", Value: "false"}}
	shop := func(dep debug.Module) *debug.BuildInfo {
		return &debug.BuildInfo{Main: debug.Module{Path: "example.com/shop", Version: "(devel)"}, Deps: []*debug.Module{&dep}, Settings: vcs}
	}
	tests := []struct {
		name string
		bi   *debug.BuildInfo
		want string
	}{
		{"no build info", nil, "(devel)"},
		{"installed with go install", &debug.BuildInfo{Main: debug.Module{Path: module, Version: "v0.3.0"}}, "v0.3.0"},
		{
			"built from a checkout with changes",
			&debug.BuildInfo{Main: debug.Module{Path: module, Version: "v0.0.0-20261026052951-3ca2f74900fe+dirty"}, Settings: vcs},
			"(devel)",
		},
		{"built from a tagged checkout", &debug.BuildInfo{Main: debug.Module{Path: module, Version: "v0.3.0"}, Settings: vcs}, "(devel)"},
		{"run with go run", &debug.BuildInfo{Main: debug.Module{Path: module, Version: "(devel)"}}, "(devel)"},
		{"run with go tool", shop(debug.Module{Path: module, Version: "v0.3.0"}), "v0.3.0"},
		{
			"run with go tool at a commit that go.mod pins",
			shop(debug.Module{Path: module, Version: "v0.3.1-0.20261026052951-3ca2f74900fe"}),
			"v0.3.1-0.20261026052951-3ca2f74900fe",
		},
		{
			"replaced by a local directory",
			shop(debug.Module{Path: module, Version: "v0.3.0", Replace: &debug.Module{Path: "/home/ana/dynaflux"}}),
			"(devel)",
		},
		{
			"replaced by a fork",
			shop(debug.Module{Path: module, Version: "v0.3.0", Replace: &debug.Module{Path: "example.com/fork/dynaflux", Version: "v0.3.1"}}),
			"v0.3.1",
		},
		{"without the module", shop(debug.Module{Path: "example.com/other", Version: "v1.0.0"}), "(devel)"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if got := cli.HeaderVersion(tt.bi); got != tt.want {
				t.Errorf("got %q, want %q", got, tt.want)
			}
		})
	}
}
