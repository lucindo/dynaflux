var update = flag.Bool("update", false, "rewrite the want/dynaflux.lock sections, and the outputs in the README and the guides, from the actual output") //nolint:gochecknoglobals // go test flags are package variables

const (
	wantPrefix = "want/"
	wantLock   = wantPrefix + "dynaflux.lock"
	// goHeader and yamlHeader are the first lines of the generated Go files and templates,
	// as a test binary sees its version.
	goHeader   = "// Code generated by dynaflux (devel). DO NOT EDIT.\n"
	yamlHeader = "# Code generated by dynaflux (devel). DO NOT EDIT.\n"
)

// generatedFiles are the files generate writes with the default go.out, runtime.out and
// infra.out.
func generatedFiles() []string {
	return []string{
		"cmd/dynaflux-runtime/main.go", "dynaflux.lock", "infra/dynaflux/global.stack-policy.json", "infra/dynaflux/global.yaml",
		"infra/dynaflux/regional.yaml", "internal/flux/catalog.go", "internal/flux/client.go", "internal/flux/queries.go",
		"internal/flux/streams.go",
	}
}

// TestGenerate runs generate on each project under testdata/generate. When it succeeds,
// it writes the four files of the client package, the templates and the lock, whose bytes
// the archive's want/dynaflux.lock holds (go test -update rewrites it; review the diff).
// When it fails, it writes nothing.
func TestGenerate(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		want result // its stderr is a prefix of the actual one
	}{
		{"new", result{0, "page_daily@v1: new\n", ""}},
		{"unchanged", result{0, "", ""}},
		{"changed", result{0, "page_daily@v1: retained\npage_daily@v2: new\n", ""}},
		{"revert", result{0, "page_daily@v1: current again\npage_daily@v2: retained\n", ""}},
		{"removed", result{0, "page_daily@v1: retained\n", ""}},
		{"two_current", result{0, "page_daily@v1: retained\n", ""}},
		{"retired", result{0, "page_daily@v2: retained\npage_daily@v3: new\n", ""}},
		{"conflict", result{1, "", "dynaflux.lock:4:1: error DF6013: can't use dynaflux.lock: invalid JSON: "}},
		{"user_file", result{1, "", "dynaflux generate: internal/flux/client.go has no \"// Code generated"}},
		{
			"user_main",
			result{1, "", "dynaflux generate: cmd/dynaflux-runtime/main.go has no \"// Code generated ... DO NOT EDIT.\" line, " +
				"so it isn't generated code; move it out of cmd/dynaflux-runtime\n"},
		},
		{"no_module", result{2, "", "dynaflux generate: no go.mod in "}},
		{
			"user_template",
			result{1, "", "dynaflux generate: infra/dynaflux/global.yaml doesn't start with a \"# Code generated ... DO NOT EDIT.\" line"},
		},
		{
			"user_policy",
			result{1, "", "dynaflux generate: infra/dynaflux/global.stack-policy.json can't carry a \"# Code generated ... DO NOT EDIT.\" " +
				"line, and there is no generated global.yaml beside it"},
		},
		{"no_stream", result{1, "", "dynaflux generate: infra: the store has no stream, so there is nothing to deploy\n"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			name := "generate/" + tt.name
			dir := writeProject(t, name)
			before := snapshot(t, dir)
			got := runAlone(dir, "generate")
			if got.status != tt.want.status || got.stdout != tt.want.stdout || !strings.HasPrefix(got.stderr, tt.want.stderr) {
				t.Fatalf("got  %+v\nwant %+v, with stderr as a prefix", got, tt.want)
			}
			after := snapshot(t, dir)
			if got.status != 0 {
				if !maps.EqualFunc(before, after, slices.Equal) {
					t.Errorf("a failed generate changed files: %q became %q", slices.Sorted(maps.Keys(before)), slices.Sorted(maps.Keys(after)))
				}
				return
			}
			checkWritten(t, before, after)
			checkLock(t, name, after["dynaflux.lock"])
		})
	}
}

// checkWritten checks that generate added exactly its files, each Go file and template
// with its header.
func checkWritten(t *testing.T, before, after map[string][]byte) {
	t.Helper()
	want := slices.Compact(slices.Sorted(slices.Values(append(slices.Collect(maps.Keys(before)), generatedFiles()...))))
	if got := slices.Sorted(maps.Keys(after)); !slices.Equal(got, want) {
		t.Errorf("files after generate: %q, want %q", got, want)
	}
	for _, p := range generatedFiles() {
		header := map[string]string{".go": goHeader, ".yaml": yamlHeader}[path.Ext(p)]
		if header != "" && !strings.HasPrefix(string(after[p]), header) {
			t.Errorf("%s doesn't start with %q", p, header)
		}
	}
}

// checkLock compares the lock that generate wrote with the archive's want/dynaflux.lock.
func checkLock(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name+".txtar")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	ar := txtar.Parse(data)
	i := slices.IndexFunc(ar.Files, func(f txtar.File) bool { return f.Name == wantLock })
	if *update {
		if i < 0 {
			ar.Files = append(ar.Files, txtar.File{Name: wantLock})
			i = len(ar.Files) - 1
		}
		ar.Files[i].Data = got
		if err = os.WriteFile(path, txtar.Format(ar), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if i < 0 {
		t.Fatalf("%s has no %s section", path, wantLock)
	}
	if want := ar.Files[i].Data; string(got) != string(want) {
		t.Errorf("dynaflux.lock:\n%s\nwant:\n%s", got, want)
	}
}

// snapshot returns every file under dir by its slash path.
func snapshot(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		files[filepath.ToSlash(rel)] = data
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

// generate writes query.yaml while a query is exposed, and deletes its own copy once none is.
// A query.yaml that generate didn't write stays.
func TestGenerateQueryTemplate(t *testing.T) {
	t.Parallel()
	const query = "infra/dynaflux/query.yaml"
	dir := writeProject(t, "generate/exposed")
	if got := run(dir, "generate"); got.status != 0 || got.stdout != "" {
		t.Fatalf("generate with an exposed query: %+v", got)
	}
	if data := snapshot(t, dir)[query]; !strings.HasPrefix(string(data), yamlHeader) {
		t.Fatalf("%s after generate:\n%s\nwant a generated template", query, data)
	}
	sql := filepath.Join(dir, "dynaflux", "queries.sql")
	data, err := os.ReadFile(sql)
	if err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(sql, []byte(strings.Replace(string(data), "-- expose: http\n", "", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	const removed = query + ": removed, since no query is annotated -- expose: http; delete its stack in every region\n"
	if got := run(dir, "generate"); got.status != 0 || got.stdout != removed {
		t.Errorf("generate without an exposed query: %+v, want stdout %q", got, removed)
	}
	if _, ok := snapshot(t, dir)[query]; ok {
		t.Errorf("%s is still there", query)
	}
	own := []byte("AWSTemplateFormatVersion: \"2010-09-09\"\n")
	if err = os.WriteFile(filepath.Join(dir, filepath.FromSlash(query)), own, 0o644); err != nil {
		t.Fatal(err)
	}
	if got := run(dir, "generate"); got.status != 0 || got.stdout != "" {
		t.Errorf("generate beside someone's query.yaml: %+v", got)
	}
	if got := snapshot(t, dir)[query]; string(got) != string(own) {
		t.Errorf("someone's %s became:\n%s", query, got)
	}
}

// -rebuild gives the current definition a new version once; the next run keeps it.
func TestGenerateRebuild(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, "generate/rebuild")
	if got := run(dir, "generate", "-rebuild", "page_daily"); got != (result{0, "page_daily@v1: retained\npage_daily@v2: new\n", ""}) {
		t.Fatalf("generate -rebuild: %+v", got)
	}
	lock, err := os.ReadFile(filepath.Join(dir, "dynaflux.lock"))
	if err != nil {
		t.Fatal(err)
	}
	checkLock(t, "generate/rebuild", lock)
	if got := run(dir, "generate"); got != (result{0, "", ""}) {
		t.Errorf("generate after -rebuild: %+v", got)
	}
	if got := run(dir, "generate", "-rebuild", "page_daily"); got != (result{0, "page_daily@v2: retained\npage_daily@v3: new\n", ""}) {
		t.Errorf("a second generate -rebuild: %+v", got)
	}
}

// -rebuild names a view that the SQL files define: not a stream, an unknown name, or a view
// that only the lock still holds.
func TestGenerateRebuildNeedsAView(t *testing.T) {
	t.Parallel()
	for _, name := range []string{"clicks", "page_views", "page_daily"} {
		dir := writeProject(t, "generate/removed")
		before := snapshot(t, dir)
		got := run(dir, "generate", "-rebuild", name)
		want := "dynaflux generate: -rebuild " + name + ": the SQL files define no view " + name + "\n"
		if got.status != 2 || !strings.HasPrefix(got.stderr, want) {
			t.Errorf("-rebuild %s: got %+v, want status 2 and stderr starting with %q", name, got, want)
		}
		if after := snapshot(t, dir); !maps.EqualFunc(before, after, slices.Equal) {
			t.Errorf("-rebuild %s changed files", name)
		}
	}
}

// A catalog that the meta table can't store is refused before anything is written.
func TestGenerateRefusesOversizedCatalog(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, "generate/new")
	// Random letters compress to about 3/4 of their size, so 500,000 pass the limit.
	const letters = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	rnd := rand.New(rand.NewPCG(1, 2))
	noise := make([]byte, 500_000)
	for i := range noise {
		noise[i] = letters[rnd.IntN(len(letters))]
	}
	view := "CREATE MATERIALIZED VIEW page_daily\nORDER BY (page, day)\nPRIMARY KEY (page)\n" +
		"AS SELECT page, toStartOfDay(event_time) AS day, count() AS views\nFROM page_views\n" +
		"WHERE page != '" + string(noise) + "'\nGROUP BY page, day;\n"
	if err := os.WriteFile(filepath.Join(dir, "dynaflux", "views.sql"), []byte(view), 0o644); err != nil {
		t.Fatal(err)
	}
	before := snapshot(t, dir)
	got := run(dir, "generate")
	const want = "dynaflux.yaml:1:1: error DF6019: the catalog takes "
	if got.status != 1 || got.stdout != "" || !strings.HasPrefix(got.stderr, want) ||
		!strings.Contains(got.stderr, " bytes compressed, more than the 350000 that the meta table can store in one item\n") {
		t.Errorf("got %+v\nwant status 1 and stderr starting with %q", got, want)
	}
	if after := snapshot(t, dir); !maps.EqualFunc(before, after, slices.Equal) {
		t.Error("a refused generate changed files")
	}
}

